SELECT 
    leaveType.Id, 
    leaveType.Label, 
    leaveType.NoticePeriod, 
    leaveType.AllowHalfDay, 
    leaveType.RequireAttachment, 
    leaveType.QuotaRequired, 
    leaveType.Quota, 
    leaveType.QuotaReplenishmentMethodId, 
    leaveType.QuotaDurationId, 
    leaveType.CarryForwardQuotaDuration, 
    leaveType.ActivitiesDetailed,
    leaveType.DurationCalculationMethodId, 
    leaveType.MaximumDurationTaken, 
    leaveType.MaximumOverBalance, 
    leaveType.MaximumRequestFrequency, 
    leaveType.MaximumLeavePerDate, 
    leaveType.EncashmentFormula, 
    leaveType.ProcessTypeId, 
    leaveType.EncashmentComponentId, 
    leaveType.PrintOutTemplateId, leaveType.DeductFromLeaveTypeId, 
    leaveType.AttendanceCodeId, 
    leaveType.AppliedToAll, 
    leaveType.RequiredServiceTimeRangeMin, 
    leaveType.RequiredServiceTimeRangeMax, 
    leaveType.SkipTenureRequirementOnCollectiveLeave, 
    leaveType.Status,
    leaveType.InsertStamp, 
    leaveType.InsertedBy, 
    leaveType.UpdateStamp, 
    leaveType.UpdatedBy,
    durationCalculationMethod.Label AS DurationCalculationMethodLabel
FROM dbo.LeaveTypes AS leaveType 
INNER JOIN dbo.HRDeskVariables AS durationCalculationMethod 
    ON leaveType.DurationCalculationMethodId = durationCalculationMethod.Id
